'use strict';
/**
 * `korbaj setup`  — wire the shortcuts into Hyprland, robustly:
 *     · absolute paths to node and to this repo (no reliance on PATH or ~)
 *     · binds by physical key code, so they work with ANY keyboard layout
 *       (with an Arabic layout active, the "W" key is not the symbol W)
 *     · exactly one `source =` line in hyprland.conf (duplicates would fire
 *       every shortcut twice: show + hide = "nothing happens")
 * `korbaj doctor` — check every link of the chain and say what is broken.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const hypr = require('./hyprland');
const { send, controlPath } = require('./control');

const ROOT = path.join(__dirname, '..');
const CONFIG_DIR = path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'hypr');
const MAIN_CONF = path.join(CONFIG_DIR, 'hyprland.conf');
const OUR_CONF = path.join(CONFIG_DIR, 'korbaj.conf');
const STATE_DIR = path.join(process.env.XDG_STATE_HOME || path.join(os.homedir(), '.local', 'state'), 'korbaj');
const LOG_FILE = path.join(STATE_DIR, 'korbaj.log');

// Physical key codes (xkb): same key regardless of layout.
const KEYS = [
  ['ALT', 25, 'toggle', 'Alt+W  summon / hide (starts it if needed)'],
  ['ALT', 54, 'passive', 'Alt+C  click-through <-> active'],
  ['ALT', 10, 'mode 1', 'Alt+1  single whip'],
  ['ALT', 11, 'mode 2', 'Alt+2  dual whips'],
  ['ALT', 12, 'mode 3', 'Alt+3  pat mode'],
  ['ALT', 39, 'skin', 'Alt+S  next skin'],
  ['ALT SHIFT', 24, 'quit', 'Alt+Shift+Q  quit'],
];

const quote = (s) => (/[^\w@%+=:,./-]/.test(s) ? `'${s.replace(/'/g, `'\\''`)}'` : s);
const cliCommand = () => `${quote(process.execPath)} ${quote(path.join(ROOT, 'bin', 'korbaj.js'))}`;

function generateConf() {
  const cli = cliCommand();
  const lines = [
    '# Generated by `korbaj setup` — do not edit; re-run the command instead.',
    '# Binds use physical key codes so they work with any keyboard layout.',
    '',
  ];
  for (const [mods, code, cmd, label] of KEYS) lines.push(`# ${label}`, `bind = ${mods}, code:${code}, exec, ${cli} ${cmd}`);
  return `${lines.join('\n')}\n`;
}

const isKorbajSource = (line) => /^\s*source\s*=.*korbaj/i.test(line) && !/^\s*#/.test(line);

async function setupHyprland() {
  const out = [];
  if (!hypr.available) {
    out.push('✗ Hyprland is not running in this session (HYPRLAND_INSTANCE_SIGNATURE is not set).');
    out.push('  `korbaj setup` only configures Hyprland. On other desktops, bind this command to a key in your');
    out.push(`  desktop's keyboard settings:  ${cliCommand()} toggle`);
    return { ok: false, text: out.join('\n') };
  }
  if (!fs.existsSync(MAIN_CONF)) {
    out.push(`✗ ${MAIN_CONF} not found. Add this line to your Hyprland config yourself:`);
    out.push(`  source = ${OUR_CONF}`);
    fs.mkdirSync(CONFIG_DIR, { recursive: true });
    fs.writeFileSync(OUR_CONF, generateConf());
    return { ok: false, text: out.join('\n') };
  }

  fs.writeFileSync(OUR_CONF, generateConf());
  out.push(`✓ wrote ${OUR_CONF}`);

  const original = fs.readFileSync(MAIN_CONF, 'utf8');
  const kept = original.split('\n').filter((l) => !isKorbajSource(l));
  const removed = original.split('\n').length - kept.length;
  while (kept.length && kept[kept.length - 1].trim() === '') kept.pop();
  kept.push('', `source = ${OUR_CONF}`, '');
  const updated = kept.join('\n');
  if (updated !== original) {
    fs.writeFileSync(`${MAIN_CONF}.korbaj-backup`, original);
    fs.writeFileSync(MAIN_CONF, updated);
  }
  out.push(removed > 1
    ? `✓ hyprland.conf had ${removed} korbaj source lines (shortcuts were firing ${removed}×) — now exactly one`
    : '✓ hyprland.conf sources korbaj.conf exactly once');

  await hypr.request('reload', 3000).catch(() => null);
  await new Promise((r) => setTimeout(r, 400));
  const check = await checkBinds();
  out.push(check.line);
  const errs = await configErrors();
  if (errs) out.push(`! Hyprland reports config errors (may be unrelated to korbaj):\n    ${errs.split('\n').join('\n    ')}`);
  return { ok: check.ok, text: out.join('\n') };
}

async function checkBinds() {
  try {
    const binds = JSON.parse(await hypr.request('j/binds', 1500));
    const ours = binds.filter((b) => typeof b.arg === 'string' && b.arg.includes('korbaj.js'));
    const toggles = ours.filter((b) => / toggle\b/.test(b.arg));
    if (toggles.length === 1) return { ok: true, count: ours.length, line: `✓ ${ours.length} korbaj shortcuts are registered in Hyprland` };
    if (toggles.length === 0) return { ok: false, count: 0, line: '✗ Hyprland has NO korbaj shortcut registered — run: korbaj setup' };
    return { ok: false, count: ours.length, line: `✗ the toggle shortcut is registered ${toggles.length}× — each press shows AND hides. Run: korbaj setup` };
  } catch (e) {
    return { ok: false, count: 0, line: `✗ could not read Hyprland binds: ${e.message}` };
  }
}

async function configErrors() {
  try {
    const t = (await hypr.request('configerrors', 1500)).trim();
    return t && !/^no errors?$/i.test(t) ? t : '';
  } catch (_) {
    return '';
  }
}

function electronBinary() {
  try {
    const p = require(path.join(ROOT, 'node_modules', 'electron'));
    return fs.existsSync(p) ? p : null;
  } catch (_) {
    return null;
  }
}

function logTail(n = 12) {
  try {
    const lines = fs.readFileSync(LOG_FILE, 'utf8').trim().split('\n');
    return lines.slice(-n).filter((l) => !/dbus|vaapi|Fontconfig/i.test(l));
  } catch (_) {
    return [];
  }
}

async function doctor() {
  const out = [];
  const ok = (c, good, bad) => { out.push(c ? `✓ ${good}` : `✗ ${bad}`); return c; };

  out.push(`  node      ${process.execPath} (${process.version})`);
  out.push(`  korbaj    ${ROOT}`);
  out.push(`  session   ${process.env.XDG_SESSION_TYPE || '?'} / ${process.env.XDG_CURRENT_DESKTOP || '?'}`);
  ok(!!electronBinary(), 'Electron binary is installed', 'Electron binary is missing — run: npm run fix-electron');

  let running = false;
  try {
    const st = JSON.parse(await send('status'));
    running = true;
    out.push(`✓ korbaj is running (visible=${st.visible}, mode=${st.mode}, skin=${st.skin}, cursor=${st.cursorSource})`);
    if (!st.visible) out.push('  → it is hidden right now; `korbaj show` brings it back');
  } catch (_) {
    out.push(`  korbaj is not running (control socket: ${controlPath()})`);
  }

  if (hypr.available) {
    try {
      const v = JSON.parse(await hypr.request('j/version', 1500));
      out.push(`✓ Hyprland ${v.tag || v.version || ''} reachable`);
    } catch (e) {
      out.push(`✗ Hyprland socket found but not answering: ${e.message}`);
    }
    if (fs.existsSync(MAIN_CONF)) {
      const n = fs.readFileSync(MAIN_CONF, 'utf8').split('\n').filter(isKorbajSource).length;
      ok(n === 1, 'hyprland.conf sources korbaj once', n === 0
        ? 'hyprland.conf does not source korbaj — run: korbaj setup'
        : `hyprland.conf sources korbaj ${n}× (every shortcut fires ${n}×) — run: korbaj setup`);
    } else {
      out.push(`✗ ${MAIN_CONF} not found`);
    }
    out.push((await checkBinds()).line);
    const errs = await configErrors();
    if (errs) out.push(`! Hyprland config errors:\n    ${errs.split('\n').slice(0, 8).join('\n    ')}`);
  } else {
    out.push('  Hyprland not detected — shortcuts must be bound in your desktop settings to:');
    out.push(`    ${cliCommand()} toggle`);
  }

  const tail = logTail();
  if (!running && tail.length) out.push(`  last log lines (${LOG_FILE}):\n    ${tail.join('\n    ')}`);
  return out.join('\n');
}

module.exports = {
  setupHyprland, doctor, electronBinary, logTail, cliCommand, LOG_FILE, STATE_DIR, ROOT,
};
